// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// early rows below the floor: the pre-token protocols the radar exists to find. A protocol is pre-token
// when its record carries no token at all (no market cap, no CoinGecko id, no symbol). Protocols whose
// token already trades are kept apart, in the dashboard's Live view, and never ranked against the board.
//
// Implied value follows only from the snapshot's own figures — TVL, seven-day change, category, how long
// the protocol has run — through one function every row shares. No name, no slug, no chain is ever
// special-cased, so the board is a claim the data makes, not a list someone wrote.
//
//   base       = tvl_usd x CATEGORY_MULTIPLE[category]   (a category's own capital efficiency)
//   growth     = clamp(change_7d, GROWTH_FLOOR, GROWTH_CAP) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS x MATURITY_RANGE
//   implied    = max(1, round(base x growthMult x maturity))

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.25,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-2';

